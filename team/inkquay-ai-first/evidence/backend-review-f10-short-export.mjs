const c=await j('/api/projects',{method:'POST',body:JSON.stringify({title:'短篇导出探针',type:'short',premise:'一个在地铁站等人的人遇见了十年前的自己。',targetWords:12000,start:'pipeline'})});
const pid=c.body.project.id;
await waitJob(pid);
await j(`/api/projects/${pid}/stages/p1/confirm`,{method:'POST',body:'{}'});
await j(`/api/projects/${pid}/pipeline/start`,{method:'POST',body:JSON.stringify({stage:'p2'})});
await waitJob(pid);
await j(`/api/projects/${pid}/stages/p2/confirm`,{method:'POST',body:'{}'});
await j(`/api/projects/${pid}/pipeline/start`,{method:'POST',body:JSON.stringify({stage:'p3'})});
await waitJob(pid);
await j(`/api/projects/${pid}/pipeline/accept-deviation`,{method:'POST',body:JSON.stringify({accepted:true})});
